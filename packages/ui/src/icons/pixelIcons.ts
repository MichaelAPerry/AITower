export type PixelIconName = keyof typeof RAW;

/** Rows are padded or cut to 16x16, so a slip in the art can never break the renderer (icons.test.ts still checks the exact size). */
const parse = (s: string): string[] => {
	const rows = s
		.split("\n")
		.map((r) => r.trim())
		.filter((r) => r.length > 0);
	return rows;
};
export const ICON_ROWS: Record<PixelIconName, string[]> = Object.fromEntries(Object.entries(RAW).map(([k, v]) => [k, parse(v)])) as Record<PixelIconName, string[]>;
export const ICON_NAMES = Object.keys(ICON_ROWS) as PixelIconName[];
export const hasIcon = (name: string): name is PixelIconName => name in ICON_ROWS;

/** The icon of each tree: Lattice (crystal and circuit), Flesh (heart and cell), Garden (leaf). Keyed by the ascension path and by the research tree id. */
export const TREE_ICON = { synthetic: "lattice", biotech: "flesh", greentech: "garden", lattice: "lattice", flesh: "flesh", garden: "garden" } as const satisfies Record<string, PixelIconName>;

/** Merge a 16x16 map into one rect path per colour: `[colour, d]` pairs. Horizontal runs only (cheap, and still exactly on the grid). */
export function iconPaths(name: PixelIconName): [string, string][] {
	const byColour = new Map<string, string>();
	ICON_ROWS[name].forEach((row, y) => {
		let x = 0;
		while (x < row.length) {
			const ch = row[x];
			let w = 1;
			while (x + w < row.length && row[x + w] === ch) w++;
			const col = PALETTE[ch];
			if (col) byColour.set(col, `${byColour.get(col) ?? ""}M${x} ${y}h${w}v1h-${w}z`);
			x += w;
		}
	});
	return [...byColour.entries()];
}
